#!/usr/bin/env python
# -*- coding: utf-8 -*-

"""Plot and summarize public concept-heldout experiment results.

The script consumes the aggregate training result table produced by
``tools/run_public_concept_heldout_sweep.py`` plus each generated dataset
manifest.  It intentionally reports only metrics present in the aggregate
table (AUC/ACC/RMSE).  Route-conditioned BCE recovery requires per-query
prediction exports and should be generated by the main-problem inference
runner, not inferred from this table.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Dict, Iterable, List

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


ROOT = Path(__file__).resolve().parents[1]

DATASET_ORDER = ["assist_09_chold", "assist_17_chold", "junyi_chold"]
VARIANT_ORDER = ["full", "no_A", "A_self_only", "A_degree_random"]
VARIANT_LABELS = {
    "full": "Full",
    "no_A": "w/o CRG",
    "A_self_only": "Self-only",
    "A_degree_random": "Degree-random",
}
DATASET_LABELS = {
    "assist_09_chold": "ASSIST09",
    "assist_17_chold": "ASSIST17",
    "junyi_chold": "Junyi",
}
COLORS = {
    "full": "#0072B2",
    "no_A": "#D55E00",
    "A_self_only": "#E69F00",
    "A_degree_random": "#999999",
}


def _read_json(path: Path) -> Dict:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def _safe_rate(num: float, den: float) -> float:
    return float(num) / float(den) if den else np.nan


def load_gap_profile(data_root: Path, datasets: Iterable[str]) -> pd.DataFrame:
    rows: List[Dict] = []
    for dataset in datasets:
        manifest_path = data_root / dataset / "manifest.json"
        if not manifest_path.exists():
            rows.append({"dataset": dataset, "manifest_exists": False})
            continue
        manifest = _read_json(manifest_path)
        splits = manifest.get("splits", {})
        gap = manifest.get("gap_profile", {})
        train_rows = int(splits.get("train", {}).get("rows", 0))
        valid_rows = int(splits.get("valid", {}).get("rows", 0))
        test_rows = int(splits.get("test", {}).get("rows", 0))
        total_rows = train_rows + valid_rows + test_rows
        test_direct_unseen = int(gap.get("test_direct_unseen_rows", 0))
        overlap = float(gap.get("test_train_concept_overlap_rate", np.nan))
        audit = manifest.get("student_split_audit", {})
        rows.append(
            {
                "dataset": dataset,
                "manifest_exists": True,
                "train_rows": train_rows,
                "valid_rows": valid_rows,
                "test_rows": test_rows,
                "total_rows": total_rows,
                "train_ratio": _safe_rate(train_rows, total_rows),
                "valid_ratio": _safe_rate(valid_rows, total_rows),
                "test_ratio": _safe_rate(test_rows, total_rows),
                "test_direct_unseen_rows": test_direct_unseen,
                "test_direct_unseen_rate": _safe_rate(test_direct_unseen, test_rows),
                "test_train_concept_overlap_rate": overlap,
                "students_with_all_splits": int(audit.get("students_with_all_splits", 0)),
                "selected_students": int(manifest.get("filter", {}).get("selected_students", 0)),
                "shuffle_within_student": bool(manifest.get("shuffle_within_student", False)),
            }
        )
    return pd.DataFrame(rows)


def load_results(result_csv: Path, datasets: Iterable[str], variants: Iterable[str]) -> pd.DataFrame:
    df = pd.read_csv(result_csv)
    missing = {"dataset", "variant", "status", "test_auc", "test_acc", "test_rmse"} - set(df.columns)
    if missing:
        raise ValueError(f"{result_csv} missing required columns: {sorted(missing)}")
    df = df[df["dataset"].isin(list(datasets)) & df["variant"].isin(list(variants))].copy()
    df["dataset"] = pd.Categorical(df["dataset"], categories=list(datasets), ordered=True)
    df["variant"] = pd.Categorical(df["variant"], categories=list(variants), ordered=True)
    return df.sort_values(["dataset", "variant"]).reset_index(drop=True)


def compute_delta_summary(df: pd.DataFrame) -> pd.DataFrame:
    rows: List[Dict] = []
    for dataset, part in df.groupby("dataset", observed=True):
        full = part[part["variant"].astype(str) == "full"]
        if full.empty:
            continue
        full_row = full.iloc[0]
        for _, row in part.iterrows():
            if str(row["variant"]) == "full":
                continue
            rows.append(
                {
                    "dataset": str(dataset),
                    "variant": str(row["variant"]),
                    "control_label": VARIANT_LABELS.get(str(row["variant"]), str(row["variant"])),
                    "full_auc": float(full_row["test_auc"]),
                    "control_auc": float(row["test_auc"]),
                    "delta_auc_full_minus_control": float(full_row["test_auc"] - row["test_auc"]),
                    "full_acc": float(full_row["test_acc"]),
                    "control_acc": float(row["test_acc"]),
                    "delta_acc_full_minus_control": float(full_row["test_acc"] - row["test_acc"]),
                    "full_rmse": float(full_row["test_rmse"]),
                    "control_rmse": float(row["test_rmse"]),
                    "delta_rmse_control_minus_full": float(row["test_rmse"] - full_row["test_rmse"]),
                    "passes_auc": bool(full_row["test_auc"] > row["test_auc"]),
                    "passes_rmse": bool(full_row["test_rmse"] < row["test_rmse"]),
                }
            )
    return pd.DataFrame(rows)


def _set_axis_style(ax) -> None:
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.grid(axis="y", color="#D9D9D9", linewidth=0.8, alpha=0.8)
    ax.set_axisbelow(True)


def plot_gap_profile(profile: pd.DataFrame, out_prefix: Path) -> None:
    profile = profile.copy()
    profile["dataset_label"] = profile["dataset"].map(DATASET_LABELS).fillna(profile["dataset"])
    x = np.arange(len(profile))
    fig, axes = plt.subplots(1, 2, figsize=(10.0, 3.8), constrained_layout=True)

    bottom = np.zeros(len(profile))
    for col, label, color in [
        ("train_ratio", "Train", "#0072B2"),
        ("valid_ratio", "Valid", "#E69F00"),
        ("test_ratio", "Test", "#009E73"),
    ]:
        axes[0].bar(x, profile[col].fillna(0), bottom=bottom, color=color, label=label, width=0.68)
        bottom += profile[col].fillna(0).to_numpy()
    axes[0].axhline(0.7, color="#666666", linestyle="--", linewidth=0.9)
    axes[0].axhline(0.8, color="#666666", linestyle=":", linewidth=0.9)
    axes[0].set_ylabel("Row ratio")
    axes[0].set_ylim(0, 1.05)
    axes[0].set_xticks(x, profile["dataset_label"])
    axes[0].set_title("Split composition")
    axes[0].legend(frameon=False, ncols=3, fontsize=9)
    _set_axis_style(axes[0])

    width = 0.34
    axes[1].bar(
        x - width / 2,
        profile["test_direct_unseen_rate"].fillna(0),
        color="#CC79A7",
        width=width,
        label="Direct-unseen in test",
    )
    axes[1].bar(
        x + width / 2,
        profile["test_train_concept_overlap_rate"].fillna(0),
        color="#999999",
        width=width,
        label="Train-test concept overlap",
    )
    for i, row in profile.iterrows():
        axes[1].text(
            i - width / 2,
            min(1.03, float(row["test_direct_unseen_rate"]) + 0.025),
            f"n={int(row['test_direct_unseen_rows']):,}",
            ha="center",
            va="bottom",
            fontsize=8,
            rotation=0,
        )
    axes[1].set_ylabel("Rate")
    axes[1].set_ylim(0, 1.12)
    axes[1].set_xticks(x, profile["dataset_label"])
    axes[1].set_title("Problem profile")
    axes[1].legend(frameon=False, fontsize=9)
    _set_axis_style(axes[1])

    for ext in ("png", "pdf"):
        fig.savefig(out_prefix.with_suffix(f".{ext}"), dpi=300, bbox_inches="tight")
    plt.close(fig)


def plot_metrics(df: pd.DataFrame, out_prefix: Path) -> None:
    datasets = [d for d in DATASET_ORDER if d in set(df["dataset"].astype(str))]
    variants = [v for v in VARIANT_ORDER if v in set(df["variant"].astype(str))]
    x = np.arange(len(datasets))
    width = min(0.18, 0.78 / max(1, len(variants)))

    fig, axes = plt.subplots(1, 2, figsize=(10.0, 3.8), constrained_layout=True)
    for j, variant in enumerate(variants):
        part = df[df["variant"].astype(str) == variant].set_index(df[df["variant"].astype(str) == variant]["dataset"].astype(str))
        offset = (j - (len(variants) - 1) / 2) * width
        auc_vals = [float(part.loc[d, "test_auc"]) if d in part.index else np.nan for d in datasets]
        rmse_vals = [float(part.loc[d, "test_rmse"]) if d in part.index else np.nan for d in datasets]
        axes[0].bar(x + offset, auc_vals, width=width, color=COLORS.get(variant, "#666666"), label=VARIANT_LABELS.get(variant, variant))
        axes[1].bar(x + offset, rmse_vals, width=width, color=COLORS.get(variant, "#666666"), label=VARIANT_LABELS.get(variant, variant))

    for ax, ylabel, title in [
        (axes[0], "AUC", "Heldout concept diagnosis"),
        (axes[1], "RMSE", "Lower is better"),
    ]:
        ax.set_xticks(x, [DATASET_LABELS.get(d, d) for d in datasets])
        ax.set_ylabel(ylabel)
        ax.set_title(title)
        _set_axis_style(ax)
    axes[0].set_ylim(max(0.55, np.nanmin(df["test_auc"]) - 0.03), min(0.90, np.nanmax(df["test_auc"]) + 0.04))
    axes[1].set_ylim(max(0.30, np.nanmin(df["test_rmse"]) - 0.03), min(0.60, np.nanmax(df["test_rmse"]) + 0.04))
    axes[0].legend(frameon=False, fontsize=9, ncols=2)

    for ext in ("png", "pdf"):
        fig.savefig(out_prefix.with_suffix(f".{ext}"), dpi=300, bbox_inches="tight")
    plt.close(fig)


def plot_deltas(delta: pd.DataFrame, out_prefix: Path) -> None:
    if delta.empty:
        return
    datasets = [d for d in DATASET_ORDER if d in set(delta["dataset"])]
    variants = [v for v in VARIANT_ORDER if v in set(delta["variant"]) and v != "full"]
    x = np.arange(len(datasets))
    width = min(0.22, 0.78 / max(1, len(variants)))
    fig, axes = plt.subplots(1, 2, figsize=(10.0, 3.8), constrained_layout=True)
    for j, variant in enumerate(variants):
        part = delta[delta["variant"] == variant].set_index("dataset")
        offset = (j - (len(variants) - 1) / 2) * width
        auc_delta = [float(part.loc[d, "delta_auc_full_minus_control"]) if d in part.index else np.nan for d in datasets]
        rmse_delta = [float(part.loc[d, "delta_rmse_control_minus_full"]) if d in part.index else np.nan for d in datasets]
        axes[0].bar(x + offset, auc_delta, width=width, color=COLORS.get(variant, "#666666"), label=VARIANT_LABELS.get(variant, variant))
        axes[1].bar(x + offset, rmse_delta, width=width, color=COLORS.get(variant, "#666666"), label=VARIANT_LABELS.get(variant, variant))

    for ax, ylabel, title in [
        (axes[0], "Full AUC - control AUC", "AUC advantage"),
        (axes[1], "Control RMSE - Full RMSE", "RMSE recovery"),
    ]:
        ax.axhline(0, color="#333333", linewidth=1.0)
        ax.set_xticks(x, [DATASET_LABELS.get(d, d) for d in datasets])
        ax.set_ylabel(ylabel)
        ax.set_title(title)
        _set_axis_style(ax)
    axes[0].legend(frameon=False, fontsize=9, ncols=2)

    for ext in ("png", "pdf"):
        fig.savefig(out_prefix.with_suffix(f".{ext}"), dpi=300, bbox_inches="tight")
    plt.close(fig)


def write_report(out_path: Path, profile: pd.DataFrame, results: pd.DataFrame, delta: pd.DataFrame) -> None:
    def _table(frame: pd.DataFrame) -> str:
        try:
            return frame.to_markdown(index=False, floatfmt=".4f")
        except ImportError:
            return "```csv\n" + frame.to_csv(index=False) + "```"

    missing = []
    for dataset in DATASET_ORDER:
        for variant in VARIANT_ORDER:
            if results[(results["dataset"].astype(str) == dataset) & (results["variant"].astype(str) == variant)].empty:
                missing.append(f"{dataset}/{variant}")

    lines = [
        "# Public Concept-Heldout Experiment Report",
        "",
        "This report summarizes aggregate training metrics for the student-conditioned concept-heldout split.",
        "It does not claim BCE recovery because the aggregate training table does not contain per-query BCE.",
        "",
        "## Gap Profile",
        "",
        _table(profile),
        "",
        "## Aggregate Metrics",
        "",
        _table(results[["dataset", "variant", "status", "test_auc", "test_acc", "test_rmse", "best_val_auc", "best_epoch"]]),
        "",
        "## Full-vs-Control Deltas",
        "",
        _table(delta) if not delta.empty else "No complete control deltas available yet.",
        "",
        "## Completion",
        "",
    ]
    if missing:
        lines.append("Incomplete controls: " + ", ".join(missing))
    else:
        all_auc = bool(delta["passes_auc"].all()) if not delta.empty else False
        all_rmse = bool(delta["passes_rmse"].all()) if not delta.empty else False
        lines.append(f"All requested aggregate runs present: yes")
        lines.append(f"Full AUC higher than every trained control: {'yes' if all_auc else 'no'}")
        lines.append(f"Full RMSE lower than every trained control: {'yes' if all_rmse else 'no'}")
    lines.append("")
    lines.append("Next required step for the paper-level main-problem claim: export aligned per-query predictions and compute route-conditioned BCE recovery.")
    out_path.write_text("\n".join(lines), encoding="utf-8")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-id", default="public_chold_full_20260529_v1")
    parser.add_argument("--datasets", default=",".join(DATASET_ORDER))
    parser.add_argument("--variants", default=",".join(VARIANT_ORDER))
    parser.add_argument("--result-csv", default=None)
    parser.add_argument("--data-root", default=str(ROOT / "data"))
    parser.add_argument("--output-dir", default=None)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    datasets = [x.strip() for x in args.datasets.split(",") if x.strip()]
    variants = [x.strip() for x in args.variants.split(",") if x.strip()]
    result_csv = Path(args.result_csv) if args.result_csv else ROOT / "results" / args.run_id / "mechanism_results.csv"
    out_dir = Path(args.output_dir) if args.output_dir else ROOT / "results" / args.run_id / "figures"
    out_dir.mkdir(parents=True, exist_ok=True)

    profile = load_gap_profile(Path(args.data_root), datasets)
    results = load_results(result_csv, datasets, variants)
    delta = compute_delta_summary(results)

    summary_dir = out_dir.parent
    profile.to_csv(summary_dir / "public_chold_gap_profile.csv", index=False)
    results.to_csv(summary_dir / "public_chold_aggregate_metrics.csv", index=False)
    delta.to_csv(summary_dir / "public_chold_full_vs_control_deltas.csv", index=False)

    plot_gap_profile(profile, out_dir / "fig_public_chold_gap_profile")
    plot_metrics(results, out_dir / "fig_public_chold_metrics")
    plot_deltas(delta, out_dir / "fig_public_chold_deltas")
    write_report(summary_dir / "public_chold_report.md", profile, results, delta)
    print(f"[DONE] wrote figures and summaries to {summary_dir}")


if __name__ == "__main__":
    main()
